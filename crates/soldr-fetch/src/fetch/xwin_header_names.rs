//! Canonical spellings of Windows SDK / CRT headers that user code includes
//! (soldr#3415).
//!
//! The xwin bundle stores one file per header under whatever casing the recipe
//! splatted (mostly lowercase: `basetsd.h`). The SDK's own headers reference
//! each other in the casing they were authored in, and the include-referenced
//! alias pass picks those up by scanning them. Code outside the SDK is not
//! scanned, and it spells headers the way Microsoft documents them --
//! `BaseTsd.h`, `WinSock2.h`, `Windows.h` -- which never appear in that casing
//! inside the SDK, so on a case-sensitive filesystem `#include <BaseTsd.h>`
//! (libssh-rs-sys, wezterm) fails with "file not found".
//!
//! This is a list of documented spellings, not a proof of coverage: a header
//! outside it and outside the SDK's own references still needs an alias
//! supplied by the caller. Extra aliases are harmless (each is only created
//! where a case-insensitive match already exists), so the list errs wide.

